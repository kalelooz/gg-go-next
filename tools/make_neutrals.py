# Builds app/src/neutrals.js: what pro players craft per hero, role and neutral tier, from OpenDota's
# player_matches.neutral_item_history. Free, read-only.
# Run once per patch: python -I tools\make_neutrals.py   (set SINCE to the patch's release first)
import json, os, time, urllib.parse, urllib.request
from collections import defaultdict

SINCE = 1774335600   # 7.41 release, 2026-03-24
MIN_CRAFTS = 50      # below this a hero's table is noise; the overlay falls back to the role table
API = 'https://api.opendota.com/api/'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'neutrals.js')
# Role from the player's GPM rank in his team, the research's role proxy: c = richest (carry),
# m = 2nd-3rd (mid, offlane), s = 4th-5th (supports). Tier = craft number, so keeping an artifact counts as "keep".
SQL = """with pm as (select pm.hero_id, pm.neutral_item_history h,
  rank() over (partition by pm.match_id, pm.player_slot < 128 order by pm.gold_per_min desc) r
  from player_matches pm join matches m using(match_id)
  where m.start_time >= {a} and m.start_time < {b} and pm.neutral_item_history is not null)
select pm.hero_id h, case when r = 1 then 'c' when r <= 3 then 'm' else 's' end g, x.ord t,
  coalesce(x.e->>'item_neutral', 'keep') a, x.e->>'item_neutral_enhancement' e, count(*) n
from pm, unnest(pm.h) with ordinality x(e, ord) where x.ord <= 5 group by 1, 2, 3, 4, 5"""
# names the constants lack (the replay's internal name for Defiant Shell)
EXTRA_NAMES = {'guardian_shell': 'Defiant Shell', 'keep': 'keep yours'}


def get(path):
    # OpenDota refuses Python's default User-Agent (403)
    req = urllib.request.Request(API + path, headers={'User-Agent': 'gg-go-next/0.1'})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)


def rows():
    # one 30-day chunk at a time: the whole range times out on OpenDota's side
    a, now = SINCE, int(time.time())
    while a < now:
        d = get('explorer?' + urllib.parse.urlencode({'sql': SQL.format(a=a, b=a + 2592000)}))
        if d.get('err'):
            raise SystemExit(f'OpenDota: {d["err"]}')
        yield from d['rows']
        a += 2592000
        time.sleep(1)


def top(counts, k):
    total = sum(counts.values())
    return [[name, round(100 * n / total)] for name, n in sorted(counts.items(), key=lambda x: -x[1])[:k]], total


if __name__ == '__main__':
    heroes, items = get('constants/heroes'), get('constants/items')
    attr = {int(h['id']): h['primary_attr'] for h in heroes.values()}
    art, role_art, enc = defaultdict(lambda: defaultdict(int)), defaultdict(lambda: defaultdict(int)), defaultdict(lambda: defaultdict(int))
    for r in rows():
        art[f'{r["h"]}:{r["g"]}:{r["t"]}'][r['a']] += r['n']
        role_art[f'{r["g"]}:{r["t"]}'][r['a']] += r['n']
        if r['e'] and r['h'] in attr:
            enc[f'{attr[r["h"]]}:{r["g"]}:{r["t"]}'][r['e']] += r['n']
    picks = {}
    for key, c in list(art.items()) + list(role_art.items()):
        t, total = top(c, 3)
        if total >= MIN_CRAFTS:
            picks[key] = t
    encs = {key: top(c, 2)[0] for key, c in enc.items() if sum(c.values()) >= MIN_CRAFTS}
    used = {n for v in list(picks.values()) + list(encs.values()) for n, _ in v}
    names = {n: EXTRA_NAMES.get(n) or items.get(n, {}).get('dname') or n.replace('_', ' ').title() for n in sorted(used)}
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/make_neutrals.py from OpenDota pro matches since 7.41. Rerun each patch.\n')
        f.write('// PICKS "heroId:role:tier" or "role:tier" -> top 3 [artifact, % of crafts]; role c carry, m mid/offlane, s support.\n')
        f.write('// ENC "attr:role:tier" -> top 2 [enchantment, %]. ATTR heroId -> primary attribute. NAMES -> display name.\n')
        for name, val in (('ATTR', attr), ('NAMES', names), ('PICKS', picks), ('ENC', encs)):
            f.write(f'export const {name} = {json.dumps(val, separators=(",", ":"))};\n')
    print(len(picks), 'pick tables,', len(encs), 'enchantment tables ->', OUT)
