// Tests for search.js. npm test runs every test file with plain node; a failed assert stops the run.
import assert from 'node:assert/strict';
import { search } from './search.js';

const top = q => search(q)[0]?.hero.name;
assert.equal(top('am'), 'Anti-Mage');
assert.equal(top('furion'), "Nature's Prophet");
assert.equal(top('np'), "Nature's Prophet");
assert.equal(top('wisp'), 'Io');
assert.equal(top('necrolyte'), 'Necrophos');
assert.equal(top('qop'), 'Queen of Pain');
assert.equal(top('pa'), 'Phantom Assassin');
assert.equal(top('kotl'), 'Keeper of the Light');
assert.equal(top('sf'), 'Shadow Fiend');
assert.equal(top('nevermore'), 'Shadow Fiend');
assert.equal(top('od'), 'Outworld Devourer');
assert.equal(top('outworld destroyer'), 'Outworld Devourer');
assert.equal(top('skeleton king'), 'Wraith King');
assert.equal(top('windrunner'), 'Windranger');
assert.equal(top('zeus'), 'Zeus');
assert.equal(top('traxex'), 'Drow Ranger');
assert.equal(top('cm'), 'Crystal Maiden');
assert.equal(top('pud'), 'Pudge');
assert.equal(top('void'), 'Faceless Void');
assert.equal(top('rubi'), 'Rubick');
assert.equal(top('BB'), 'Bristleback');
assert.equal(top('Anti Mage'), 'Anti-Mage');
assert.equal(search('furion')[0].via, 'furion');
assert.equal(search('pudge')[0].via, null);
assert.equal(search('qop')[0].via, 'qop');
assert.equal(search('ta')[0].via, null);
assert.deepEqual(search(''), []);
assert.equal(search('am', new Set([1])).some(r => r.hero.id === 1), false);
assert.ok(search('a').length <= 6);
console.log('search ok');
